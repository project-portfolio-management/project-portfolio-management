-- 20261114000112_public_roadmap_slugs (RE-8): a public product roadmap's earlier slugs, kept so an old link still
-- finds it. A slug, current or earlier, belongs to one roadmap only, and is never given to another.

CREATE TABLE public_roadmap_slugs (
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    roadmap_id bigint NOT NULL REFERENCES public_roadmaps (id) ON DELETE CASCADE,
    slug varchar NOT NULL,
    CONSTRAINT public_roadmap_old_slug CHECK (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$' AND length(slug) <= 64)
);

CREATE UNIQUE INDEX public_roadmap_old_slug_once ON public_roadmap_slugs (slug);
