CREATE TABLE IF NOT EXISTS "skill_pools" ( "created_at" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP, "updated_at" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP, "id" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY, "pid" uuid NOT NULL UNIQUE, "name" varchar NOT NULL, "active" bool NOT NULL );

CREATE TABLE IF NOT EXISTS "skill_pool_members" ( "created_at" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP, "updated_at" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP, "id" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY, "pid" uuid NOT NULL UNIQUE, "pool_pid" uuid NOT NULL, "kind" varchar NOT NULL, "value" varchar NOT NULL );

CREATE TABLE IF NOT EXISTS "capacity_commitments" ( "created_at" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP, "updated_at" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP, "id" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY, "pid" uuid NOT NULL UNIQUE, "pool_pid" uuid NOT NULL, "plan_pid" uuid NOT NULL, "organization" varchar NULL, "kind" varchar NOT NULL, "month" date NOT NULL, "committed_milli_fte" integer NOT NULL, "delivered_milli_fte" integer NULL, "note" text NULL, "updated_by" varchar NULL );

CREATE UNIQUE INDEX skill_pools_name ON skill_pools (lower(name));

ALTER TABLE skill_pool_members ADD CONSTRAINT spm_kind CHECK (kind IN ('role','skill'));

CREATE UNIQUE INDEX spm_once ON skill_pool_members (kind, lower(value));

ALTER TABLE capacity_commitments ADD CONSTRAINT cc_kind CHECK (kind IN ('supply','demand'));

ALTER TABLE capacity_commitments ADD CONSTRAINT cc_month CHECK (month = date_trunc('month', month)::date);

ALTER TABLE capacity_commitments ADD CONSTRAINT cc_amounts CHECK (committed_milli_fte BETWEEN 0 AND 1000000 AND (delivered_milli_fte IS NULL OR delivered_milli_fte BETWEEN 0 AND 1000000));

CREATE UNIQUE INDEX cc_once ON capacity_commitments (pool_pid, plan_pid, coalesce(lower(organization), ''), kind, month);

CREATE INDEX cc_by_month ON capacity_commitments (month);
