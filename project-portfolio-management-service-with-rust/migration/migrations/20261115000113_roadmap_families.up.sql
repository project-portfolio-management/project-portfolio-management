-- 20261115000113_roadmap_families (RE-5, RE-7): a product family's colour, chosen by its editors.
--
-- A product family is a plan that holds product plans (RE-7: the family is the parent plan, so there is no family
-- table of names). What a family adds is its own: a colour, any `#rrggbb` its editors choose, stored lower case, and
-- its name in other languages. One row per family plan; a plan with no row has no colour. As for `public_roadmaps`,
-- `plan_pid` has no foreign key: plans are deleted softly, and reads join on a live plan.

CREATE TABLE roadmap_families (
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    plan_pid uuid NOT NULL UNIQUE,
    colour varchar NOT NULL,
    translations jsonb NOT NULL DEFAULT '{}'::jsonb,
    CONSTRAINT roadmap_family_colour CHECK (colour ~ '^#[0-9a-f]{6}$'),
    CONSTRAINT roadmap_family_translations CHECK (jsonb_typeof(translations) = 'object')
);
