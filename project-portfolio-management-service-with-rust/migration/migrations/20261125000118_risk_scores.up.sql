-- 20261125000118_risk_scores: an append-only history of every risk's probability and impact (OF-3 step 1).
-- A trigger writes it, so no path (create, update, import, canvas) changes a score without a row.
-- The handler sets ppm.actor and ppm.reason for the transaction; a path that sets none leaves them empty.
-- A risk scored before this migration gets one row marked as the first known score, not its true history.

CREATE TABLE IF NOT EXISTS risk_scores (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    risk_pid uuid NOT NULL,
    probability integer NOT NULL,
    impact integer NOT NULL,
    score integer NOT NULL,
    recorded_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actor varchar NULL,
    reason text NULL,
    backfilled boolean NOT NULL DEFAULT false
);

CREATE INDEX IF NOT EXISTS risk_scores_by_risk ON risk_scores (risk_pid, recorded_at, id);

INSERT INTO risk_scores (risk_pid, probability, impact, score, recorded_at, backfilled)
SELECT pid, probability, impact, probability * impact, CURRENT_TIMESTAMP, true FROM risks;

CREATE OR REPLACE FUNCTION risk_scores_write() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'INSERT' OR NEW.probability IS DISTINCT FROM OLD.probability OR NEW.impact IS DISTINCT FROM OLD.impact THEN
    INSERT INTO risk_scores (risk_pid, probability, impact, score, actor, reason)
    VALUES (NEW.pid, NEW.probability, NEW.impact, NEW.probability * NEW.impact,
            nullif(current_setting('ppm.actor', true), ''), nullif(current_setting('ppm.reason', true), ''));
  END IF;
  RETURN NEW;
END $$;

CREATE TRIGGER risk_scores_write AFTER INSERT OR UPDATE ON risks FOR EACH ROW EXECUTE FUNCTION risk_scores_write();

CREATE OR REPLACE FUNCTION risk_scores_guard() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF current_setting('ppm.audit_pseudonymise', true) = 'on' AND TG_OP = 'UPDATE' THEN RETURN NEW; END IF;
  RAISE EXCEPTION 'risk score history is append-only';
END $$;

CREATE TRIGGER risk_scores_guard BEFORE UPDATE OR DELETE ON risk_scores FOR EACH ROW EXECUTE FUNCTION risk_scores_guard();
