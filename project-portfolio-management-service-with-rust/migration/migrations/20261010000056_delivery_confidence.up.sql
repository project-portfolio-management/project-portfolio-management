CREATE TABLE IF NOT EXISTS "delivery_confidence_assessments" ( "created_at" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP, "updated_at" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP, "id" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY, "pid" uuid NOT NULL UNIQUE, "plan_pid" uuid NOT NULL, "value" varchar NOT NULL, "kind" varchar NOT NULL, "rationale" text NOT NULL, "assessor" varchar NULL, "assessed_on" date NOT NULL );

CREATE TABLE IF NOT EXISTS "delivery_exceptions" ( "created_at" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP, "updated_at" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP, "id" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY, "pid" uuid NOT NULL UNIQUE, "plan_pid" uuid NOT NULL, "status" varchar NOT NULL, "opened_at" timestamp with time zone NOT NULL, "opened_by" varchar NULL, "opened_value" varchar NOT NULL, "worst_value" varchar NOT NULL, "worsened_count" integer NOT NULL, "cause" text NULL, "decision_needed" text NULL, "owner_ref" varchar NULL, "owner_role" varchar NULL, "decide_by" date NULL, "completed_at" timestamp with time zone NULL, "breach_notified_at" timestamp with time zone NULL, "closed_at" timestamp with time zone NULL, "decision" text NULL, "decided_by" varchar NULL );

CREATE TABLE IF NOT EXISTS "strategic_aims" ( "created_at" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP, "updated_at" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP, "id" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY, "pid" uuid NOT NULL UNIQUE, "objective_pid" uuid NOT NULL, "marked_by" varchar NULL );

