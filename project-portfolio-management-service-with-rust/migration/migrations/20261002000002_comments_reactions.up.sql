-- What the Rust migration said of itself:
--
-- Migration: **`comments`**, **`comment_edits`** and **`reactions`**
-- (LT-4). One generic pair keyed `(subject_kind, subject_pid)` serves
-- every commentable thing (plan, task, risk, proposal, idea, canvas
-- item), so a new subject kind is code, not a migration.
--
-- - `comments` soft-delete; the author is the token `sub` (nothing
--   identity-shaped beyond it) and may be absent only when auth is off.
-- - `comment_edits` is append-only: the previous body of every edit is
--   kept, so a discussion cannot be silently rewritten.
-- - `reactions` are one per `(subject, sub, kind)` — the unique index
--   makes a repeat reaction idempotent by construction.

CREATE TABLE IF NOT EXISTS "comments" ( "created_at" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP, "updated_at" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP, "id" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY, "pid" uuid NOT NULL UNIQUE, "subject_kind" varchar NOT NULL, "subject_pid" uuid NOT NULL, "author_sub" varchar NULL, "body" text NOT NULL, "edited_at" timestamp with time zone NULL, "deleted_at" timestamp with time zone NULL );

CREATE TABLE IF NOT EXISTS "comment_edits" ( "created_at" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP, "updated_at" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP, "id" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY, "comment_pid" uuid NOT NULL, "previous_body" text NOT NULL, "edited_by" varchar NULL );

CREATE TABLE IF NOT EXISTS "reactions" ( "created_at" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP, "updated_at" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP, "id" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY, "pid" uuid NOT NULL UNIQUE, "subject_kind" varchar NOT NULL, "subject_pid" uuid NOT NULL, "sub" varchar NOT NULL, "kind" varchar NOT NULL );

CREATE INDEX comments_subject ON comments (subject_kind, subject_pid, id) WHERE deleted_at IS NULL;

CREATE INDEX comment_edits_comment ON comment_edits (comment_pid, id);

CREATE UNIQUE INDEX reactions_one_per_user ON reactions (subject_kind, subject_pid, sub, kind);
