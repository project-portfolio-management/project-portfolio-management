-- What the Rust migration said of itself:
--
-- Migration: **`canvases`** and **`canvas_items`** — strategy canvases
-- (LT-1). One generic pair of tables serves every canvas type (Lean,
-- Business Model, SWOT, …): a canvas names a `template` key, and each
-- item names a `box_key` within that template. The template (an ordered
-- box list) lives in code (`src/canvas.rs`), so adding a canvas type is
-- data, not a migration.
--
-- A canvas is optionally scoped to a plan (`plan_pid`); a free-standing
-- canvas is the pre-proposal "what are we trying to do?" case. An item
-- may later be **promoted** to an idea, risk or objective; the link back
-- is recorded on the item (`promoted_to_*`) so a promotion is
-- idempotent-by-refusal, never silently repeated.

CREATE TABLE IF NOT EXISTS "canvases" ( "created_at" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP, "updated_at" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP, "id" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY, "pid" uuid NOT NULL UNIQUE, "plan_pid" uuid NULL, "template" varchar NOT NULL, "title" varchar NOT NULL, "description" text NULL, "deleted_at" timestamp with time zone NULL );

CREATE TABLE IF NOT EXISTS "canvas_items" ( "created_at" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP, "updated_at" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP, "id" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY, "pid" uuid NOT NULL UNIQUE, "canvas_pid" uuid NOT NULL, "box_key" varchar NOT NULL, "body" text NOT NULL, "owner_ref" varchar NULL, "position" integer NOT NULL, "promoted_to_kind" varchar NULL, "promoted_to_pid" uuid NULL, "deleted_at" timestamp with time zone NULL );

CREATE INDEX canvases_plan ON canvases (plan_pid) WHERE deleted_at IS NULL;

CREATE INDEX canvas_items_canvas ON canvas_items (canvas_pid, box_key, position) WHERE deleted_at IS NULL;

ALTER TABLE canvas_items ADD CONSTRAINT canvas_items_promotion_pair CHECK ((promoted_to_kind IS NULL) = (promoted_to_pid IS NULL));
