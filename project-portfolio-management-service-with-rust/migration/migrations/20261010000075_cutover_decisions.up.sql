-- Migration: **go / no-go for safety-critical cutovers** (EX-6). A cutover decision has stop criteria that
-- are published before the decision opens and cannot be edited afterwards (a new version is made instead),
-- each marked met or not while it is open, and co-signatures from configured roles. "Go" needs every
-- criterion met and every co-signature; "no-go" and "delay for safety" are decisions in their own right.
-- The database holds the freeze: criteria change only while the decision is a draft.

CREATE TABLE IF NOT EXISTS "cutover_decisions" ( "created_at" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP, "updated_at" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP, "id" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY, "pid" uuid NOT NULL UNIQUE, "plan_pid" uuid NOT NULL, "title" varchar NOT NULL, "version" integer NOT NULL, "supersedes_pid" uuid NULL, "status" varchar NOT NULL, "published_on" date NULL, "opened_on" date NULL, "outcome" varchar NULL, "decided_on" date NULL, "decided_by" varchar NULL, "decision_reason" text NULL );

CREATE TABLE IF NOT EXISTS "cutover_criteria" ( "created_at" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP, "updated_at" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP, "id" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY, "pid" uuid NOT NULL UNIQUE, "decision_pid" uuid NOT NULL, "position" integer NOT NULL, "criterion" text NOT NULL, "met" bool NULL, "evidence" text NULL, "marked_by" varchar NULL, "marked_on" date NULL );

CREATE TABLE IF NOT EXISTS "cutover_cosignatures" ( "created_at" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP, "updated_at" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP, "id" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY, "pid" uuid NOT NULL UNIQUE, "decision_pid" uuid NOT NULL, "role" varchar NOT NULL, "signed_by" varchar NULL, "signed_on" date NOT NULL );

ALTER TABLE cutover_decisions ADD CONSTRAINT cd_status CHECK (status IN ('draft','published','open','decided','superseded'));

