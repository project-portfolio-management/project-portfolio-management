-- 20261114000110_roadmap_lists (RE-7): lists defined once, which a public product roadmap links to by id.
--
-- The first migration written for sqlx after the freeze (SQ-1): it has no `seaql_migrations` name, and the bridge
-- never sees it.
--
-- * An organization gains an optional short code, unique ignoring case, and a national scope that one organization
--   at most may hold (in NHS Wales, `National` for All Wales beside the health boards' codes).
-- * `roadmap_categories`: a category a public product roadmap is filed under, with its name and its translations.

ALTER TABLE organizations ADD COLUMN code varchar NULL;

ALTER TABLE organizations ADD COLUMN national bool NOT NULL DEFAULT false;

ALTER TABLE organizations ADD CONSTRAINT org_code CHECK (code IS NULL OR code ~ '^[A-Za-z0-9][A-Za-z0-9-]{0,19}$');

CREATE UNIQUE INDEX org_code_once ON organizations (lower(code)) WHERE code IS NOT NULL;

CREATE UNIQUE INDEX org_one_national ON organizations ((true)) WHERE national;

CREATE TABLE roadmap_categories (
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    pid uuid NOT NULL UNIQUE,
    name varchar NOT NULL,
    translations jsonb NOT NULL DEFAULT '{}'::jsonb,
    active bool NOT NULL DEFAULT true,
    CONSTRAINT roadmap_category_name CHECK (length(btrim(name)) BETWEEN 1 AND 100),
    CONSTRAINT roadmap_category_translations CHECK (jsonb_typeof(translations) = 'object')
);

CREATE UNIQUE INDEX roadmap_category_name_once ON roadmap_categories (lower(btrim(name)));
