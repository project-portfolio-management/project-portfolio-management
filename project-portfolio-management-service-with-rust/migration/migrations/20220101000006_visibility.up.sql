CREATE TABLE IF NOT EXISTS "plan_dependencies" ( "created_at" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP, "updated_at" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP, "id" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY, "pid" uuid NOT NULL UNIQUE, "predecessor_pid" uuid NOT NULL, "successor_pid" uuid NOT NULL, "lag_days" integer NOT NULL );

CREATE TABLE IF NOT EXISTS "milestones" ( "created_at" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP, "updated_at" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP, "id" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY, "pid" uuid NOT NULL UNIQUE, "plan_pid" uuid NOT NULL, "name" varchar NOT NULL, "due" date NOT NULL, "done" bool NOT NULL DEFAULT FALSE, "deleted_at" timestamp with time zone NULL );

CREATE TABLE IF NOT EXISTS "allocations" ( "created_at" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP, "updated_at" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP, "id" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY, "pid" uuid NOT NULL UNIQUE, "plan_pid" uuid NOT NULL, "person_ref" varchar NOT NULL, "role" varchar NULL, "percent" integer NOT NULL, "start_date" date NULL, "end_date" date NULL, "deleted_at" timestamp with time zone NULL );

CREATE TABLE IF NOT EXISTS "report_definitions" ( "created_at" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP, "updated_at" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP, "id" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY, "pid" uuid NOT NULL UNIQUE, "name" varchar NOT NULL, "collection" varchar NOT NULL, "filters" jsonb NOT NULL, "fields" jsonb NOT NULL, "deleted_at" timestamp with time zone NULL );

CREATE UNIQUE INDEX IF NOT EXISTS dependencies_pair ON plan_dependencies (predecessor_pid, successor_pid);

CREATE INDEX IF NOT EXISTS milestones_item ON milestones (plan_pid);

CREATE INDEX IF NOT EXISTS allocations_item ON allocations (plan_pid);

CREATE INDEX IF NOT EXISTS allocations_person ON allocations (person_ref) WHERE deleted_at IS NULL;
