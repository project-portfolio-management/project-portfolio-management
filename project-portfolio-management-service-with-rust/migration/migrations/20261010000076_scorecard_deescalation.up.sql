CREATE TABLE IF NOT EXISTS "scorecards" ( "created_at" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP, "updated_at" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP, "id" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY, "pid" uuid NOT NULL UNIQUE, "name" varchar NOT NULL, "for_deescalation" bool NOT NULL, "active" bool NOT NULL );

CREATE TABLE IF NOT EXISTS "scorecard_kpis" ( "created_at" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP, "updated_at" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP, "id" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY, "pid" uuid NOT NULL UNIQUE, "scorecard_pid" uuid NOT NULL, "kpi_pid" uuid NOT NULL );

CREATE TABLE IF NOT EXISTS "escalation_levels" ( "created_at" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP, "updated_at" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP, "id" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY, "pid" uuid NOT NULL UNIQUE, "level" varchar NOT NULL, "note" text NULL, "set_by" varchar NULL, "set_on" date NOT NULL );

CREATE TABLE IF NOT EXISTS "deescalation_criteria" ( "created_at" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP, "updated_at" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP, "id" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY, "pid" uuid NOT NULL UNIQUE, "criterion" text NOT NULL, "active" bool NOT NULL );

CREATE TABLE criterion_evidence (
                 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                 pid UUID NOT NULL UNIQUE,
                 criterion_pid UUID NOT NULL,
                 quarter VARCHAR NOT NULL,
                 met BOOLEAN NOT NULL,
                 link TEXT,
                 note TEXT NOT NULL,
                 recorded_by VARCHAR,
                 recorded_on DATE NOT NULL
             );

CREATE UNIQUE INDEX sc_name ON scorecards (lower(btrim(name)));

CREATE UNIQUE INDEX sc_one_deescalation ON scorecards (for_deescalation) WHERE for_deescalation;

CREATE UNIQUE INDEX sck_once ON scorecard_kpis (scorecard_pid, kpi_pid);

ALTER TABLE escalation_levels ADD CONSTRAINT el_level CHECK (length(btrim(level)) BETWEEN 1 AND 60);

ALTER TABLE criterion_evidence ADD CONSTRAINT ce_quarter CHECK (quarter ~ '^[0-9]{4}-Q[1-4]$');

ALTER TABLE criterion_evidence ADD CONSTRAINT ce_note CHECK (length(btrim(note)) >= 5);

ALTER TABLE criterion_evidence ADD CONSTRAINT ce_link CHECK (link IS NULL OR link ~ '^https?://[^ ]+$');

CREATE INDEX ce_by_criterion ON criterion_evidence (criterion_pid, quarter, id);

CREATE OR REPLACE FUNCTION ex10_append_only() RETURNS trigger LANGUAGE plpgsql AS $$
             BEGIN
               IF TG_OP = 'UPDATE' AND coalesce(current_setting('ppm.audit_pseudonymise', true), '') = 'on' THEN RETURN NEW; END IF;
               RAISE EXCEPTION 'escalation levels and evidence are append-only';
             END $$;

CREATE TRIGGER el_append_only BEFORE UPDATE OR DELETE ON escalation_levels FOR EACH ROW EXECUTE FUNCTION ex10_append_only();

CREATE TRIGGER ce_append_only BEFORE UPDATE OR DELETE ON criterion_evidence FOR EACH ROW EXECUTE FUNCTION ex10_append_only();
