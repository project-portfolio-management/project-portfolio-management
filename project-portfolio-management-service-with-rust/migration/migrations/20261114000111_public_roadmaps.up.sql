-- 20261114000111_public_roadmaps (RE-1, RE-6): a product plan's public product roadmap and its items.
--
-- * `public_roadmaps`: one per plan, with a public address (`slug`), its own text, a category (RE-7), whether it is
--   published, and the date someone last said it was reviewed (RE-3), which no other write changes.
-- * `public_roadmap_items`: what the product is doing, each in a placement (or none: unplaced, never public), in an
--   order within it, with a public id of eight characters that is never reused (a removed item keeps its row).
-- * `translations` on both: language code to field to `{ value, source }`, where `source` is the hash of the text
--   the translation was made from. A translation whose source has changed since reads as needing review (RE-6).

CREATE TABLE public_roadmaps (
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    pid uuid NOT NULL UNIQUE,
    plan_pid uuid NOT NULL UNIQUE,
    slug varchar NOT NULL,
    title text NOT NULL,
    vision text NULL,
    service_description text NULL,
    category_pid uuid NULL,
    published bool NOT NULL DEFAULT false,
    reviewed_on date NULL,
    translations jsonb NOT NULL DEFAULT '{}'::jsonb,
    CONSTRAINT public_roadmap_slug CHECK (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$' AND length(slug) <= 64),
    CONSTRAINT public_roadmap_title CHECK (length(btrim(title)) BETWEEN 1 AND 200),
    CONSTRAINT public_roadmap_translations CHECK (jsonb_typeof(translations) = 'object')
);

CREATE UNIQUE INDEX public_roadmap_slug_once ON public_roadmaps (slug);

CREATE TABLE public_roadmap_items (
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    pid uuid NOT NULL UNIQUE,
    roadmap_id bigint NOT NULL REFERENCES public_roadmaps (id) ON DELETE CASCADE,
    public_id varchar NOT NULL,
    title text NOT NULL,
    description text NULL,
    expected_outcome text NULL,
    phase text NULL,
    tags jsonb NOT NULL DEFAULT '[]'::jsonb,
    organization_pids uuid[] NOT NULL DEFAULT '{}',
    details jsonb NOT NULL DEFAULT '[]'::jsonb,
    placement varchar NULL,
    position integer NOT NULL DEFAULT 0,
    translations jsonb NOT NULL DEFAULT '{}'::jsonb,
    deleted_at timestamp with time zone NULL,
    CONSTRAINT public_roadmap_item_public_id CHECK (public_id ~ '^[a-z][a-z0-9]{7}$'),
    CONSTRAINT public_roadmap_item_title CHECK (length(btrim(title)) BETWEEN 1 AND 200),
    CONSTRAINT public_roadmap_item_placement CHECK (placement IS NULL OR placement IN
        ('recently_delivered', 'now', 'next', 'later', 'delivered_this_year', 'not_doing')),
    CONSTRAINT public_roadmap_item_lists CHECK (jsonb_typeof(tags) = 'array' AND jsonb_typeof(details) = 'array'),
    CONSTRAINT public_roadmap_item_translations CHECK (jsonb_typeof(translations) = 'object')
);

CREATE UNIQUE INDEX public_roadmap_item_public_id_once ON public_roadmap_items (public_id);

CREATE INDEX public_roadmap_items_in_order ON public_roadmap_items (roadmap_id, placement, position);
