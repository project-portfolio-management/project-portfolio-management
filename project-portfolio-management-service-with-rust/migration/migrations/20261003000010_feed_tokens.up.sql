-- Migration: **`feed_tokens`**. Revocable secrets that let a calendar app or feed reader read one person's own feeds without a bearer token (LT-7 / RM-6). Only the SHA-256 of the token is stored, so a database read never yields a usable token; revoking sets `revoked_at` and takes effect on the next fetch.

CREATE TABLE IF NOT EXISTS "feed_tokens" ( "created_at" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP, "updated_at" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP, "id" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY, "pid" uuid NOT NULL UNIQUE, "sub" varchar NOT NULL, "token_hash" varchar NOT NULL, "label" varchar NULL, "revoked_at" timestamp with time zone NULL, "last_used_at" timestamp with time zone NULL );

CREATE UNIQUE INDEX feed_tokens_hash ON feed_tokens (token_hash);

CREATE INDEX feed_tokens_sub ON feed_tokens (sub);
